import { PKG_NAME } from "../meta";
import type { Profile } from "../profiles";
import { PRESET_IDS } from "../rules";

export const AGENT_DIRS = [
  ".agent", ".agents", ".claude", ".codex", ".continue", ".cursor",
  ".gemini", ".opencode", ".pi", ".roo", ".windsurf",
];

export const camel = (name: string): string => name.replace(/-(\w)/g, (_, c: string) => c.toUpperCase());

const presetImports = (profile: Profile): string =>
  profile.presets.map((p) => `import ${camel(p)} from "./tools/oxlint/presets/${p}.ts";`).join("\n");

export function renderConfig(profile: Profile): string {
  const ignores = [...AGENT_DIRS.map((d) => `${d}/**`), "tools/oxlint/**", "oxlint-kit-staging/**", ".oxlint-kit-backup/**"];
  return (
    `import { defineConfig } from "oxlint";\n\n${presetImports(profile)}\n\n` +
    `export default defineConfig({\n  extends: [${profile.presets.map(camel).join(", ")}],\n` +
    `  ignorePatterns: ${JSON.stringify(ignores, null, 2).replace(/\n/g, "\n  ")},\n` +
    `  // Your overrides go here. Presets in tools/oxlint/presets are regenerated by \`npx ${PKG_NAME} update\`.\n` +
    `  rules: {},\n});\n`
  );
}

export const configReferencesPresets = (text: string): boolean => text.includes("tools/oxlint/presets");

/** True when the config imports exactly the presets of this profile. */
export const configImportsMatch = (text: string, profile: Profile): boolean =>
  PRESET_IDS.every((p) => text.includes(`presets/${p}.ts`) === profile.presets.includes(p));

export const configSnippet = (profile: Profile): string =>
  `${presetImports(profile)}\n\n  extends: [${profile.presets.map(camel).join(", ")}],`;
