import { PKG_NAME, PKG_VERSION } from "../meta";
import type { Profile } from "../profiles";
import { PRESET_PLUGINS, RULES, type Layer, type Mode, type PresetId, type RuleSpec } from "../rules";

export const severity = (layer: Layer, mode: Mode): "error" | "warn" =>
  layer === "hard" || mode === "strict" ? "error" : "warn";

export function presetRules(preset: PresetId, profile: Profile, mode: Mode): Record<string, unknown> {
  const specs: RuleSpec[] = [...RULES[preset]];
  if (preset === "base") {
    specs.push([
      "unicorn/filename-case",
      "soft",
      {
        cases: profile.filenameCases,
        ...(profile.filenameIgnores.length ? { ignore: profile.filenameIgnores } : {}),
      },
    ]);
  }
  if (preset === "strict" && profile.noTernary) specs.push(["eslint/no-ternary", "soft"]);

  const rules: Record<string, unknown> = {};
  for (const [name, layer, options] of specs) {
    const level = severity(layer, mode);
    rules[name] = options === undefined ? level : [level, options];
  }
  return rules;
}

const literal = (value: unknown): string => JSON.stringify(value, null, 2).replace(/\n/g, "\n  ");

export function generatedHeader(profile: Profile, mode: Mode): string {
  return (
    `// Generated by ${PKG_NAME}@${PKG_VERSION} (profile: ${profile.id}, mode: ${mode}). Do not edit: run \`npx ${PKG_NAME} update\`.\n` +
    `// Project-specific overrides belong in oxlint.config.ts.\n`
  );
}

export function renderPreset(preset: PresetId, profile: Profile, mode: Mode): string {
  const header = generatedHeader(profile, mode);
  const rules = literal(presetRules(preset, profile, mode));

  if (preset === "anti-slop") {
    const overrides = profile.uiFiles.length
      ? `\n  overrides: [\n    {\n      files: ${JSON.stringify(profile.uiFiles)},\n      rules: { "anti-slop/no-object-parameters": "off" },\n    },\n  ],`
      : "";
    return (
      `${header}import { fileURLToPath } from "node:url";\n\nimport { defineConfig } from "oxlint";\n\n` +
      `const entry = fileURLToPath(new URL("../anti-slop/index.ts", import.meta.url));\n\n` +
      `export default defineConfig({\n  jsPlugins: [{ name: "anti-slop", specifier: entry }],\n  rules: ${rules},${overrides}\n});\n`
    );
  }

  if (preset === "sonar") {
    return (
      `${header}import { defineConfig } from "oxlint";\n\n` +
      `export default defineConfig({\n  jsPlugins: [{ name: "sonarjs", specifier: "eslint-plugin-sonarjs" }],\n  rules: ${rules},\n});\n`
    );
  }

  return (
    `${header}import { defineConfig } from "oxlint";\n\n` +
    `export default defineConfig({\n  plugins: ${JSON.stringify(PRESET_PLUGINS[preset])},\n  rules: ${rules},\n});\n`
  );
}

/** Preset text without the generated header, for comparing across CLI versions. */
export const presetBody = (text: string): string =>
  text
    .split("\n")
    .filter((line) => !line.startsWith("// Generated by") && !line.startsWith("// Project-specific"))
    .join("\n");
