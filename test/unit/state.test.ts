import { mkdirSync, mkdtempSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { afterEach, beforeEach, describe, expect, it } from "vitest";
import { hashDir } from "../../src/core/hash";
import { projectPaths, type ProjectPaths } from "../../src/core/paths";
import { installedSettings, vendoredOwnership } from "../../src/core/state";

let root: string;
let paths: ProjectPaths;
beforeEach(() => {
  root = mkdtempSync(join(tmpdir(), "oxkit-state-"));
  paths = projectPaths(root);
});
afterEach(() => rmSync(root, { recursive: true, force: true }));

const writeVendored = (content = "export {};\n") => {
  mkdirSync(paths.vendored, { recursive: true });
  writeFileSync(join(paths.vendored, "index.ts"), content);
};
const writeLegacyLock = () =>
  writeFileSync(paths.legacyLock, JSON.stringify({ sha: "a".repeat(40), contentHash: hashDir(paths.vendored) }));

describe("vendoredOwnership", () => {
  it("is none without a vendored copy", () => expect(vendoredOwnership(paths)).toBe("none"));

  it("is unknown without any record", () => {
    writeVendored();
    expect(vendoredOwnership(paths)).toBe("unknown");
  });

  it("adopts a clean legacy install", () => {
    writeVendored();
    writeLegacyLock();
    expect(vendoredOwnership(paths)).toBe("legacy");
  });

  it("flags local edits", () => {
    writeVendored();
    writeLegacyLock();
    writeFileSync(join(paths.vendored, "index.ts"), "export const edited = true;\n");
    expect(vendoredOwnership(paths)).toBe("edited");
  });
});

it("reads legacy settings from the preset header", () => {
  mkdirSync(paths.presets, { recursive: true });
  writeFileSync(
    join(paths.presets, "base.ts"),
    "// Generated by install-lint.mjs (profile: ts, mode: strict). Do not edit: re-run the installer.\n",
  );
  expect(installedSettings(paths)).toMatchObject({ profile: "ts", mode: "strict", source: "legacy" });
});
