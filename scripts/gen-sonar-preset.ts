// Generates src/rules/sonar.generated.ts from the installed eslint-plugin-sonarjs.
// Run: bun run gen:sonar  (regenerate after bumping eslint-plugin-sonarjs; checked by prepublishOnly).
import { createRequire } from "node:module";
import { writeFileSync } from "node:fs";

const require = createRequire(import.meta.url);
const sonar = require("eslint-plugin-sonarjs") as {
  rules: Record<string, { meta?: { docs?: { requiresTypeChecking?: boolean } } }>;
};

/** Registered by the plugin but unhelpful under oxlint; reasons matter for the next maintainer. */
const ALWAYS_OFF: Record<string, string> = {
  "no-reference-error": "bridge provides no globals; rule errors on every file",
  "file-header": "errors on every file without per-project config",
  "arrow-function-convention": "conflicts with the formatter",
  "cognitive-complexity": "set explicitly in the hand-curated preset",
};

/** Oxlint's JS bridge gives plugins no type information: type-aware rules would silently do nothing. */
const isTypeAware = (rule: { meta?: { docs?: { requiresTypeChecking?: boolean } } }): boolean =>
  rule.meta?.docs?.requiresTypeChecking === true;

const entries = Object.entries(sonar.rules).map(([name, rule]) => {
  if (isTypeAware(rule)) return `  ["sonarjs/${name}", "off"], // type-aware: no type info through the JS bridge`;
  if (ALWAYS_OFF[name]) return `  ["sonarjs/${name}", "off"], // ${ALWAYS_OFF[name]}`;
  return `  ["sonarjs/${name}", "soft"],`;
});

const header =
  `// Generated by scripts/gen-sonar-preset.ts from eslint-plugin-sonarjs — do not edit.\n` +
  `// Regenerate: bun run gen:sonar\n` +
  `// "off" entries exist so a rule can never be enabled by mistake in overrides.\n\n`;

const body = `export const GENERATED_SONAR_RULES: readonly (readonly [name: string, layer: "hard" | "soft" | "off"])[] = [\n${entries.join("\n")}\n];\n`;

writeFileSync(new URL("../src/rules/sonar.generated.ts", import.meta.url), header + body);
const enabled = entries.filter((e) => e.endsWith('"soft"],')).length;
console.log(`sonar.generated.ts: ${enabled} enabled, ${entries.length - enabled} off, ${entries.length} total`);
